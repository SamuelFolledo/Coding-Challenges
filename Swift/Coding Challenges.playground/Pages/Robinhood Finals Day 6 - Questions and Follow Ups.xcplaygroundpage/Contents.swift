 ## Part 5: Questions Carlos may ask you afterward, and how to answer

 - **"How do you think it went?"**
   Give a specific, honest answer — one thing that went well, one thing you'd do differently if
   you could redo it. Recruiters read a canned "great, I think it went really well!" as low-signal;
   specificity builds trust and can even help him advocate for you internally. This is a template for
   the *shape* of a good answer, not a prediction — swap in what actually happens:
   > "I felt strong on the technical screen — the sliding-window problem clicked quickly and I was
   > able to talk through the O(n) approach clearly before coding. I was less happy with how I handled
   > the retain-cycle question in the fundamentals portion — I got to the right answer, but I hedged
   > out loud for a bit before committing to it, so I'd want to be sharper and more decisive on that
   > kind of question next time."

 - **"Do you have other offers/timelines we should know about?"**
   Only share if true — this is a legitimate lever to speed up the process, don't fabricate urgency.

 - **"Any concerns after today that I can help clarify?"**
   This is a real opening — if a question in the foundation call rattled you or you're unsure how a
   tradeoff landed, ask Carlos directly whether he can get informal signal. Better to surface it now
   than sit with it silently.

 - **"Are you still comfortable with the IC3 band we discussed?"**
   If your gut says you performed above IC3 level in the loop (especially the foundation call), it's
   fair to say so directly: *"After today I feel like the scope of what I've done is closer to IC4 —
   is that something the panel can weigh before extending an offer, or is that a conversation for
   after I start?"* Worst case he says the level is fixed; you lose nothing by asking.

