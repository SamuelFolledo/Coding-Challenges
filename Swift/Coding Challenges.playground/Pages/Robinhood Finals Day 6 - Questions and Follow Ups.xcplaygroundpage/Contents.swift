 ## Part 1: Questions to ask the technical-screen interviewer

 Save these for the last 3-5 minutes. Pick 2, not all of them — a long list reads as reciting rather
 than genuine curiosity.

 - "How much of the day-to-day work looks like what we just did versus more systems-level design?"
 - "What does code review culture look like — how much time do engineers spend reviewing vs. writing?"
 - "Is there a standard architecture across iOS teams here, or does each team choose its own?"
 - "What's something about the codebase that surprised you when you joined?"

 ---

 ## Part 2: Questions to ask the project-call interviewer

 - "How do most feature teams handle state management today — is there a house style (MVVM, Redux-
   style, plain `@Observable`), or does it vary team to team?"
 - "How is UI testing handled here — snapshot tests, XCUITest, or mostly manual QA?"
 - "What does the design hand-off process look like — how much ambiguity do engineers typically
   resolve themselves versus going back to design?"

 ---

 ## Part 3: Questions to ask the foundation-call interviewer

 This person is likely more senior/tenured — good source for org-level context.

 - "What's the biggest technical challenge the iOS org is working through right now?"
 - "How does the team decide what's worth paying down as tech debt versus shipping around?"
 - "What does the path from IC3 to IC4 typically look like in terms of scope, not just tenure?"
 - "Is there a project you worked on that you'd point to as 'this is what great engineering work
   looks like here'?"

 ---

 ## Part 4: Follow-up "thank you" email templates

 Send within 24 hours, to Carlos (who can forward, or to interviewers directly if you have their
 emails). Keep it to 3-4 sentences — long thank-you notes get skimmed, not read.

