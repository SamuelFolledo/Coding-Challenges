 # Fanatics Prep — Day 1: The 30-Minute Foundation Call

 The recruiter described three pieces: a **30-minute foundation call**, a **LeetCode-style round**,
 and an **"iOS-style" round**. This page is for the first of those. A 30-minute call is short — there's
 no time for a deep technical dive, so it's almost certainly recruiter-and-rapport plus a light
 background/behavioral pass, possibly with a hiring manager rather than pure HR-recruiter. Treat it as
 the call where your **pitch (Day 0, Part 6)** and **"why this role" framing (Day 0, Part 2)** need to
 be tight and rehearsed, not the call to dive into KMP internals unprompted.

 ## Contents
 - Part 1: What 30 minutes realistically covers
 - Part 2: Likely opening questions and how to answer them
 - Part 3: Questions to ask back
 - Part 4: Comp & leveling — how to raise it if it doesn't come up
 - Part 5: Logistics checklist

 ---

 ## Part 2 preview note

 With only 30 minutes, expect roughly: 2 min intro, 5–8 min "tell me about yourself"/pitch, 10–15 min
 background/behavioral questions and role framing, 5–8 min your questions, wrap-up. Budget your pitch
 to genuinely fit in under a minute (Day 0, Part 6 is already sized for this) — a 3-minute answer here
 eats a third of the whole call.

 ---

 ## Part 1: What 30 minutes realistically covers

 Given the short format, the most efficient prep isn't more content — it's **tightening what you
 already have**. Concretely:

 - Rehearse the Day 0, Part 6 pitch out loud until it's genuinely ~45–60 seconds, not read off a page.
 - Have one clean, one-sentence answer for "why Fanatics" that isn't just "why fintech/payments" — you
   already have credit-card-domain overlap *and* a specific technical reason (Wallet/native
   ownership) to want this exact role, which most candidates won't have.
 - Assume this call is also implicitly screening for **communication clarity under time pressure** —
   given the role is "sole iOS point of contact" on a cross-platform team, how clearly you explain a
   technical tradeoff to a non-iOS-fluent listener is itself a signal, not just content.

 ---

 ## Part 2: Likely opening questions and how to answer them

 **"Tell me about yourself."**
 Use the Day 0, Part 6 pitch. Don't restate your resume line by line — the call is 30 minutes, and a
 recruiter/hiring manager has already read the resume.

 **"Why are you looking to leave PayPal / why now?"**
 Keep this forward-looking, not a complaint about the current role. A safe, honest shape: growth into
 more ownership than a large, established team structure typically hands one engineer — which pairs
 naturally with "and that's exactly what this sole-iOS-owner role offers" (ties directly back to Day 0,
 Part 2's day-to-day reasoning, which is worth surfacing here even in a short call).

 **"What do you know about Fanatics / this role?"**
 This is your chance to show you did real homework, not generic enthusiasm. Lead with the specific,
 unusual fact you already know: it's a KMP/Go team where you'd be the sole iOS specialist, and name
 the Apple Wallet example unprompted if there's room — it's concrete, technically correct, and shows
 you're already thinking like the person they're trying to hire.

 **"Walk me through a project you're proud of."**
 This likely overlaps with what a deeper technical/project-focused round would ask later in the loop —
 keep the *30-minute-call version* short (2–3 sentences: what it was, your role, the outcome), not the
 full deep-dive version. If a fuller project story is wanted, that's what the iOS-style round (Day 5)
 or a later round is for.

 **"What are you looking for in terms of comp / timeline / other processes?"**
 See Part 4.

 ---

 ## Part 3: Questions to ask back

 Keep this to 3–5 given the short call length — pick what's most useful to *you* right now, not an
 exhaustive list.

 **Process & format**
 - "You mentioned a new interview process starting mid-August — can you walk me through what the
   LeetCode-style round and the iOS-style round each actually look like? Is the iOS round more
   live-coding, system design, or conceptual discussion?"
 - "Are the two technical rounds separate calls, or combined into one session?"
 - "Who will I be meeting for each round — can I get names/titles ahead of time?"

 **Team & role — this is where your KMP/Go question belongs**
 - "You mentioned I'd likely be the only iOS engineer on a team that otherwise works in Kotlin
   Multiplatform and Go — how is iOS-specific code organized today: is there an existing `expect`/
   `actual` pattern in place, or would I be helping establish that structure?"
 - "Is there a second iOS hire planned, or is this genuinely a long-term single-iOS-owner setup?"
 - "Does the Credit Card team share business logic only through KMP, or UI code too (Compose
   Multiplatform)?" *(Day 0, Part 4 flags this as worth confirming early.)*

 **Culture / candor**
 - "What's the biggest challenge the last person in an iOS-on-a-cross-platform-team role ran into
   here?" *(if there was a predecessor — worth asking directly whether there was one)*

 Avoid asking for interview answers or anything that puts the recruiter in an awkward spot — same rule
 as any recruiter call.

 ---

 ## Part 4: Comp & leveling — how to raise it if it doesn't come up

 Per Day 0, Part 5, the only number in hand is the JD's posted **$152k–$200k base**, unconfirmed
 against any specific level. If comp doesn't come up naturally, it's fair to raise directly on a
 recruiter-style call — that's what this call is partly for:

 > "The posting lists $152k–$200k base — where in that range would this req typically land for
 > someone with my background, and is that base-only or does it include target equity/bonus?"

 Don't negotiate a number yet — there's no offer. The goal here is information: what level this maps
 to, what the full comp structure looks like (equity is common at a company Fanatics' size), and
 whether "sole iOS owner" scope is reflected in leveling at all.

 ---

 ## Part 5: Logistics checklist

 - [ ] Time the Day 0, Part 6 pitch out loud — trim until it's under 60 seconds.
 - [ ] Confirm the call's format (phone vs. video) and platform ahead of time.
 - [ ] Have 3–5 questions from Part 3 picked and prioritized, in case time runs short.
 - [ ] Ask directly what the new (2026-08-13-onward) LeetCode-style and iOS-style rounds look like —
       this is the single highest-value question on this call, since Days 2–5 are built on inference,
       not confirmation.
 - [ ] Re-read your own resume bullets the morning of — assume every bullet is fair game later in the
       loop even if this call stays high-level.

