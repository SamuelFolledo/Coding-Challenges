 ## Part 3: The loop, at a glance

 ```
 Call                  | Format                    | What's graded
 -----------------------+---------------------------+--------------------------------------------
 1. Technical screen    | CoderPad, Leetcode-style  | Problem ID, plan-first approach, code
                        | (parts 1 & 2 in one hour) | quality/refactoring, testability, debug skill
 2. Project call        | Live Xcode, blank project | UI state management, reacting to user input,
                        | (docs allowed)            | clear data flow, ability to reason out loud
 3. Foundation call     | Conversational, no code   | Depth on one real project: tech, impact,
                        |                           | team size, deadlines, how success was measured
 ```

 **The one piece of advice repeated for the technical screen: don't dive into code immediately.**
 Restate the problem, ask clarifying questions, sketch the plan and complexity out loud, get a nod
 from the interviewer, *then* start typing in CoderPad. This is graded as its own skill, separate
 from whether you get the right answer.

 ---

 ## Part 4: Comp & leveling — how to talk about it

 - You don't need to negotiate on this call. The goal is information, not a counter-offer — there's
   no offer yet.
 - Comp is already confirmed here, not a live negotiation point: the recruiter told Samuel after the
   first round that he's being considered at IC3, $133k-150k base. The JD's posted Zone 1 (NY) range
   ($166k-195k) is for a broader spread of levels on the req and isn't the number in play. If comp
   comes up again, the useful thread isn't the number itself — it's making the 6-12 month promotion
   path concrete: *"I'm comfortable with the IC3 band given the promotion path we discussed — what
   would that path actually look like in practice, in terms of review process and timing?"*
 - Don't over-promise on timeline ("I can start whenever") unless that's true — recruiters use this
   to sequence other candidates.

 ---

 ## Part 5: Logistics checklist before the calls

