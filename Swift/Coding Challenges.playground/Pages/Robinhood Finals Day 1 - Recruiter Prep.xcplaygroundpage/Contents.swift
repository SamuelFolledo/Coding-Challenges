 - [ ] Have a notepad ready for each call to jot the interviewer's name and what they emphasized.
 - [ ] Pick the one project you'll use for the foundation call now (see Day 5) so you're not
       deciding under pressure.
 - [ ] Re-read your own resume bullet points the morning of — assume every bullet is fair game.

