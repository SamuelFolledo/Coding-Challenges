 ## Part 2: Questions to ask Carlos

 Keep these light — this call is mostly logistics and rapport, not interrogation. Pick 4–6.

 **Process & scheduling**
 - "Are the three calls back-to-back on the same day, or spread across different days?"
 - "Who will I be meeting with for each of the three calls — can you share names/titles ahead of
   time so I can look them up?"
 - "Is the project call evaluated by the same rubric as the technical screen, or does it map to a
   different competency (e.g. UI/product sense vs. raw algorithms)?"
 - "What does the timeline look like after these three calls — when should I expect to hear back?"

 **Leveling & comp** (fine to ask directly, this is what recruiters are for)
 - "You mentioned IC3 as the target level — what specifically would move the needle toward IC4 at
   offer stage vs. the 6–12 month promotion path?"
 - "Is the $133k–150k a base-only band, or does it include target equity/bonus? What does total comp
   typically look like at IC3 here?"
 - "If the panel feels I'm performing above IC3, is there room to revisit leveling before an offer is
   written, or is that locked in from the recruiter screen?"

 **Team & role**
 - "Which team(s) is this req for? Is it a specific team match or a general mobile pool?"
 - "What does the iOS codebase look like today — SwiftUI adoption, or still heavy UIKit?"

 **Culture / candor**
 - "What's one thing candidates are consistently surprised by in this loop?"
 - "What feedback do you usually hear from candidates who didn't pass the project call specifically?"

 Avoid: asking Carlos to give you interview answers, or anything that puts him in an awkward spot
 relative to the hiring team. He's an ally, but he's not the one grading you.

